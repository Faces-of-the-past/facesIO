"""Data model for artworks and the collections they come from.

Each museum / archive gets its own `Artwork` subclass (e.g. `ArtworkRKD`),
responsible for parsing one record of that source's native format into the
common `Artwork` fields. A `Collection` reads a whole source file and picks the
right subclass through its `adapter` argument.

See UML diagram at docs/classes.png

The UML diagram can be generated by running:
pyreverse src/facesIO/classes.py -o png --output-directory docs
"""

import json
from lxml import etree as ET
from dataclasses import dataclass, asdict, field
from typing import Self
from facesIO.parsers import iter_rkd_records

SOURCE_PRADO = "data/prado_example.rdf"
SOURCE_RKD = "data/rkd_example.xml"

@dataclass
class Artwork:
    """A single artwork, in a source-independent representation.

    Attributes
    ----------
    id : str
        Identifier of the artwork. TODO: within the source, or global?
    title : str
        Artwork title.
    artist : str
        Name of the main artist. We assume every artwork has one.
    museum : str
        Name of the collection the artwork comes from (e.g. "Prado").
    medium : str
        Material / technique (e.g. "oil on canvas"). TODO: controlled vocabulary?
    images : list[str]
        URLs or paths to images of the artwork.
    sitter_ids : list[str]
        Identifiers of the people depicted.
    raw : str
        Path to the source file the artwork was read from, so the full original
        record can be looked up later.
    """

    id: str
    title: str = None
    artist: str = None
    museum: str = None
    medium: str = None
    images: list[str] = None
    sitter_ids: list[str] = None
    raw: str = None

    def __str__(self) -> str:
        """ Human-friendly name """
        return f"{self.museum}-{self.id} : {self.title}"

    def as_dict(self) -> dict:
        """ Returns the artwork as a dictionary """
        return asdict(self)

    def as_jsonl_line(self) -> str:
        """ Returns the artwork as a line ready to be appended to a jsonl file"""
        return json.dumps(asdict(self), ensure_ascii=False) + '\n'

    @classmethod # Like staticmethod, but inheritable
    def from_jsonl_line(cls, line: str) -> Self:
        """ Loads the artwork from a jsonl line """
        return cls(**json.loads(line))

class ArtworkRKD(Artwork): # Inherits the dataclass features (repr, eq, fields) from Artwork
    """An artwork read from one RKD XML record.

    Parameters
    ----------
    record : lxml.etree.Element
        A ``<record>`` element from an RKD XML export.
    """

    def __init__(self, record : ET.Element) -> None:
        self.id=record.get("priref") # We can use get because priref is an attribute
        self.title=record.findtext("benaming_kunstwerk")
        # Main artist: the first current ("huidig") attribution, not a rejected ("verworpen") one.
        # Fall back to the first attribution of any status.
        self.artist=(record.findtext("toeschrijving[status='huidig']/naam")
                     or record.findtext("toeschrijving/naam"))
        self.museum="RKD"
        self.images=[m.findtext("media.reference_number") for m in record.findall("media")]
        self.sitter_ids=[sitter.findtext("naam_voorgestelde") for sitter in record.findall("voorgestelde")]
        self.raw = record.getroottree().docinfo.URL

