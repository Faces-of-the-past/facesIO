"""Data model for artworks and the collections they come from.

Each museum / archive gets its own `Collection` subclass, responsible for
parsing that source's native format into a list of common `Artwork` objects.

See UML diagram at docs/classes.png

The UML diagram can be generated by running:
pyreverse src/facesIO/classes.py -o png --output-directory docs
"""

import xml.etree.ElementTree as ET
from abc import ABC, abstractmethod
from dataclasses import dataclass

from rdflib import Graph

PRADO_SOURCE = "data/prado_example.rdf"
RKD_SOURCE = "data/rkd_example.xml"


@dataclass
class Artwork(ABC):
    """A single artwork, in a source-independent representation.

    Attributes
    ----------
    id : str
        Identifier of the artwork. TODO: within the source, or global?
    title : str
        Artwork title.
    artists : List[str]
        Artwork author(s).
    museum : str
        Name of the collection the artwork comes from (e.g. "Prado").
    medium : str
        Material / technique (e.g. "oil on canvas"). TODO: controlled vocabulary?
    images : List[str]
        URLs or paths to images of the artwork.
    sitter_ids : List[str]
        Identifiers of the people depicted.
    extra : dict
        Source-specific metadata not covered by the fields above.
    """

    id: str
    title: str = None
    artists: str = None
    museum: str = None
    medium: str = None
    images: list[str] = None
    sitter_ids: list[str] = None
    raw: str = None

@dataclass
class Collection(ABC):
    """Abstract base for a collection of artworks read from a single source.

    Subclasses must implement `read_from_file` and `import_raw`.

    Attributes
    ----------
    raw      : str
        The raw file containing all the collection information. We keep it here
        as a reference, in case we need further information down the line.
    artworks : List[Artwork]
        Artworks contained in the collection.
    """

    raw: str
    artworks: list[Artwork]

    # The methods below deliberately do NOTHING. Their ONLY functionality is to fail
    # if not implemented by an underlying class.

    @abstractmethod
    def import_raw(self):
        """ Import the whole raw file
        # TODO: consider turning this and its implementations into static methods.
        # We might reuse them inside of Artwork to retrieve the extra information from file.
        """

    @abstractmethod
    def read_from_file(self, path) -> list[Artwork]:
        """Parse a source file into a list of artworks.

        Parameters
        ----------
        path : str
            Path to the file to parse.

        Returns
        -------
        List[Artwork]
            Artworks found in the file.
        """


